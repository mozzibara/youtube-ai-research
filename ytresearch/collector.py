"""Collect directly available captions, retaining provenance and timings."""
from urllib.parse import parse_qs, urlparse
import re

from .storage import atomic_write, digest, json_text, video_dir

VIDEO_RE = re.compile(r"^[a-zA-Z0-9_-]{11}$")


def video_id_from_url(value):
    value = value.strip()
    if VIDEO_RE.fullmatch(value):
        return value
    u = urlparse(value)
    hostname = (u.hostname or "").lower()
    if hostname in ("youtube.com", "www.youtube.com", "m.youtube.com") and u.path == "/watch":
        ids = parse_qs(u.query).get("v", [])
        if ids and VIDEO_RE.fullmatch(ids[0]):
            return ids[0]
    if hostname == "youtu.be":
        vid = u.path.strip("/").split("/")[0]
        if VIDEO_RE.fullmatch(vid):
            return vid
    if hostname in ("youtube.com", "www.youtube.com") and (u.path.startswith("/shorts/") or u.path.startswith("/live/")):
        vid = u.path.split("/")[2]
        if VIDEO_RE.fullmatch(vid):
            return vid
    raise ValueError(f"지원되지 않는 YouTube URL 또는 Video ID: {value}")


def choose_transcript(candidates, languages=("ko", "en")):
    candidates = list(candidates)
    for language in languages:
        for autogenerated in (False, True):
            for item in candidates:
                if item.language_code == language and item.is_generated == autogenerated:
                    return item
    # 영상의 다른 원문 언어가 있는 경우 그 언어의 수동/자동 자막을 사용한다.
    for autogenerated in (False, True):
        for item in candidates:
            if item.is_generated == autogenerated:
                return item
    raise RuntimeError("사용 가능한 원문 자막이 없습니다. 수동 가져오기가 필요합니다.")


def collect(root, video_id):
    try:
        from youtube_transcript_api import YouTubeTranscriptApi
    except ImportError as exc:
        raise RuntimeError("pip install -r requirements.txt 명령으로 의존성을 설치하십시오.") from exc
    api = YouTubeTranscriptApi()
    selected = choose_transcript(api.list(video_id))
    fetched = selected.fetch()
    snippets = fetched.snippets if hasattr(fetched, "snippets") else fetched
    segments = []
    for index, item in enumerate(snippets, start=1):
        text = str(item.text).strip()
        if not text:
            continue
        segments.append({
            "id": f"s{index:06d}",
            "start": round(float(item.start), 3),
            "duration": round(float(item.duration), 3),
            "text": text,
        })
    if not segments:
        raise RuntimeError("가져온 자막에 텍스트가 없습니다.")
    payload = {
        "video_id": video_id,
        "source_url": f"https://www.youtube.com/watch?v={video_id}",
        "language_code": selected.language_code,
        "language": selected.language,
        "is_generated": bool(selected.is_generated),
        "segments": segments,
    }
    raw = json_text(payload)
    path = video_dir(root, video_id)
    atomic_write(path / "transcript.json", raw, immutable=True)
    atomic_write(path / "transcript.sha256", digest(raw) + "\n", immutable=True)
    human = "".join(f"[{x['id']} @ {x['start']:.2f}s] {x['text']}\n" for x in segments)
    atomic_write(path / "transcript.txt", human, immutable=True)
    return digest(raw), len(segments)


def ingest_vtt(root, video_id, vtt_path, language_code="und"):
    """Import a legitimately obtained WebVTT transcript when automatic fetching fails.

    Preserves only timed cue text, not exact styled WebVTT formatting; retains the
    original .vtt bytes unchanged in the project for later verification.
    """
    import html
    from pathlib import Path

    def to_seconds(value):
        parts = value.strip().replace(",", ".").split(":")
        if len(parts) not in (2, 3):
            raise ValueError("WebVTT 시간 표기가 올바르지 않습니다.")
        result = 0.0
        for part in parts:
            result = result * 60 + float(part)
        return result

    vtt_path = Path(vtt_path)
    content = vtt_path.read_text(encoding="utf-8-sig")
    if "WEBVTT" not in content[:128]:
        raise ValueError("WEBVTT 헤더가 없습니다.")
    lines = content.replace("\r\n", "\n").split("\n")
    cues, i = [], 0
    while i < len(lines):
        line = lines[i].strip()
        if "-->" not in line:
            i += 1
            continue
        left, right = line.split("-->", 1)
        right = right.strip().split(" ", 1)[0]
        try:
            start, end = to_seconds(left), to_seconds(right)
        except (ValueError, IndexError):
            i += 1
            continue
        i += 1
        text_parts = []
        while i < len(lines) and lines[i].strip():
            # Keep plain transcript text, not markup; original VTT retained separately.
            stripped = re.sub(r"<[^>]*>", "", lines[i])
            stripped = html.unescape(stripped).strip()
            if stripped:
                text_parts.append(stripped)
            i += 1
        text = " ".join(text_parts).strip()
        if text and end >= start:
            cues.append({"id": f"s{len(cues)+1:06d}", "start": start, "duration": end-start, "text": text})
    if not cues:
        raise RuntimeError("WebVTT에서 타임스탬프가 포함된 자막을 찾지 못했습니다.")
    payload = {
        "video_id": video_id,
        "source_url": f"https://www.youtube.com/watch?v={video_id}",
        "language_code": language_code,
        "language": "VTT imported",
        "is_generated": None,
        "source_method": "manual_webvtt",
        "segments": cues,
    }
    raw = json_text(payload)
    path = video_dir(root, video_id)
    atomic_write(path / "original.vtt", content, immutable=True)
    atomic_write(path / "transcript.json", raw, immutable=True)
    atomic_write(path / "transcript.sha256", digest(raw) + "\n", immutable=True)
    atomic_write(path / "transcript.txt", "".join(f"[{s['id']} @ {s['start']:.2f}s] {s['text']}\n" for s in cues), immutable=True)
    return digest(raw), len(cues)


def ingest_json3(root, video_id, json3_file, language="ko"):
    """Deterministically parse a YouTube JSON3 subtitle file and persist immutable transcript artifacts."""
    from .multimodal import now_iso, parse_json3_subtitles

    content = json3_file.read_text(encoding="utf-8")
    parsed = parse_json3_subtitles(content, video_id=video_id, language=language)
    segments = parsed["segments"]
    if not segments:
        raise RuntimeError("JSON3 file has no usable subtitle segments")
    payload = {
        "schema_version": 1,
        "video_id": video_id,
        "collected_at": now_iso(),
        "language": language,
        "is_generated": None,
        "source_method": "youtube_json3",
        "raw_event_count": parsed["raw_event_count"],
        "time_range_ms": parsed["time_range_ms"],
        "segments": segments,
    }
    raw = json_text(payload)
    path = video_dir(root, video_id)
    atomic_write(path / "original.json3", content, immutable=True)
    atomic_write(path / "transcript.json", raw, immutable=True)
    atomic_write(path / "transcript.sha256", digest(raw) + "\n", immutable=True)
    atomic_write(path / "transcript.txt", "".join(f"[{s['id']} @ {s['start']:.2f}s] {s['text']}\n" for s in segments), immutable=True)
    return digest(raw), len(segments)

