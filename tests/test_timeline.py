"""Timeline-first extraction runs without semantic JSON schemas or report drafting."""
import contextlib
import io
import json
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch

from ytresearch.agent import Agy
from ytresearch.pipeline import chunk_text
from ytresearch.storage import atomic_write, digest, json_text, read_json, video_dir
from ytresearch.timeline import _run_agy_text, _timeline_prompt, timeline_one, export_timeline


class ChronologicalNotesTests(unittest.TestCase):
    video_id = "Tst00000054"

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        (self.root / "config").mkdir()
        self.config = {
            "extractor": {"model": "gemini-3.8-flash-medium", "effort": "medium"},
            "max_chars_per_chunk": 65,
            "max_retries": 0, "archive_agy_responses": True,
            "agy_output_format": "stream-json",
        }
        atomic_write(self.root / "config" / "agents.json", json_text(self.config))
        source = {
            "video_id": self.video_id,
            "segments": [
                {"id": f"s{i:06d}", "start": float(i * 10),
                 "duration": 2.0, "text": "짧은 원본 자막입니다"}
                for i in range(1, 5)
            ],
        }
        self.videodir = video_dir(self.root, self.video_id)
        raw = json_text(source)
        atomic_write(self.videodir / "transcript.json", raw)
        atomic_write(self.videodir / "transcript.sha256", digest(raw) + "\n")

    def tearDown(self):
        self.temp.cleanup()

    def test_timeline_prompt_has_all_segment_ids_and_no_json_schema_requirement(self):
        group = read_json(self.videodir / "transcript.json")["segments"]
        prompt = _timeline_prompt(group, 1, 1)
        self.assertIn("[s000001 @", prompt)
        self.assertIn("[s000004 @", prompt)
        self.assertIn("타임스탬프", prompt)
        self.assertIn("최종 심층 분석", prompt)
        self.assertIn("JSON Schema는 없습니다", prompt)
        self.assertNotIn("claims.section", prompt)

    def test_every_chunk_saved_raw_then_reused_without_new_model_calls(self):
        class TimelineRunner:
            def __init__(self):
                self.prompts = []
            def run_timeline(self, prompt, context):
                self.prompts.append((prompt, context))
                return "## 시간순 기록\n" + prompt.split("[순서와 근거 ID가 있는 원본 자막]\n")[1], {
                    "model": "offline-test"
                }
        runner = TimelineRunner()
        with contextlib.redirect_stdout(io.StringIO()):
            count = timeline_one(self.root, self.video_id, runner)
        self.assertGreater(count, 1)
        self.assertEqual(len(runner.prompts), count)
        notes_dir = self.videodir / "timeline"
        for i in range(1, count + 1):
            notes = (notes_dir / f"chunk_{i:03d}.md").read_text(encoding="utf-8")
            record = read_json(notes_dir / f"chunk_{i:03d}.json")
            self.assertIn("## 시간순 기록", notes)
            self.assertEqual(record["notes_sha256"], digest(notes))
            self.assertEqual(record["model"], "offline-test")
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(timeline_one(self.root, self.video_id, runner), count)
        self.assertEqual(len(runner.prompts), count)

    def test_export_full_transcript_and_all_chronological_notes(self):
        class Runner:
            def run_timeline(self, prompt, context):
                return "00:00:10 근거 [s000001]\n기술 설명과 출처", {
                    "model": "gemini-test"
                }
        with contextlib.redirect_stdout(io.StringIO()):
            count = timeline_one(self.root, self.video_id, Runner())
            folder = export_timeline(self.root, self.video_id)
            again = export_timeline(self.root, self.video_id)
        self.assertEqual(folder, again)
        manifest = read_json(folder / "manifest.json")
        self.assertEqual(manifest["transcript_segments"], 4)
        self.assertEqual(manifest["chunk_count"], count)
        self.assertEqual(len(manifest["chunks"]), count)
        self.assertEqual(manifest["final_analysis"], "ChatGPT Web; not generated by agy")
        source = (folder / "transcript.md").read_text(encoding="utf-8")
        for i in range(1, 5):
            self.assertIn(f"[s{i:06d} @", source)
        for i in range(1, count + 1):
            notes = (folder / "timeline" / f"chunk_{i:03d}.md").read_text(encoding="utf-8")
            self.assertIn("not a fact-checked report", notes)
            self.assertIn("기술 설명과 출처", notes)
            self.assertIn("Segment IDs:", notes)
        self.assertFalse((self.root / "data" / "videos" / self.video_id / "extraction.json").exists())

    def test_export_refuses_incomplete_or_tampered_or_edited_output(self):
        class Runner:
            def run_timeline(self, prompt, context):
                return "Detailed evidence [s000001]", {"model": "test"}
        with self.assertRaisesRegex(RuntimeError, "TIMELINE_EXPORT_INCOMPLETE"):
            export_timeline(self.root, self.video_id)
        with contextlib.redirect_stdout(io.StringIO()):
            timeline_one(self.root, self.video_id, Runner())
        first_note = self.videodir / "timeline" / "chunk_001.md"
        first_note.write_text("modified model content", encoding="utf-8")
        with self.assertRaisesRegex(RuntimeError, "TIMELINE_EXPORT_NOTES_TAMPERED"):
            export_timeline(self.root, self.video_id)
        with self.assertRaisesRegex(RuntimeError, "TIMELINE_CACHE_TAMPERED"):
            timeline_one(self.root, self.video_id, Runner())

    def test_cli_model_text_is_not_forced_into_json_schema(self):
        agent = self.root / ".agents" / "agents" / "yt-research-no-tools.md"
        atomic_write(agent, "---\nname: yt-research-no-tools\ntools: []\n---\n")
        arbitrary = "## 00:00:10\n문서 형식과 관계 없이 분석 아닌 기록 [s000001]"
        with patch("ytresearch.agent.shutil.which", return_value="agy.exe"):
            runner = Agy(self.root)
        completed = subprocess.CompletedProcess(
            ["agy"], 0,
            json.dumps({"status": "SUCCESS", "response": arbitrary}, ensure_ascii=False), "",
        )
        with patch.object(Agy, "_invoke", return_value=completed) as spy:
            with contextlib.redirect_stdout(io.StringIO()):
                text, info = _run_agy_text(
                    self.root, runner, "source-only chronological prompt",
                    {"video_id": self.video_id, "unit": "timeline_001"},
                )
        self.assertEqual(text, arbitrary)
        self.assertEqual(info["model"], "gemini-3.8-flash-medium")
        command = spy.call_args.args[0]
        self.assertNotIn("--json-schema", command)
        self.assertIn("--output-format", command)
        archives = list((self.root / "data" / "diagnostics" / "agy"
                         / self.video_id / "timeline").glob("*/stdout.raw.txt"))
        self.assertEqual(len(archives), 1)
        self.assertEqual(json.loads(archives[0].read_text(encoding="utf-8"))["response"], arbitrary)

    def test_cli_model_rejects_empty_reply_but_keeps_diagnostic(self):
        agent = self.root / ".agents" / "agents" / "yt-research-no-tools.md"
        atomic_write(agent, "---\nname: yt-research-no-tools\ntools: []\n---\n")
        with patch("ytresearch.agent.shutil.which", return_value="agy.exe"):
            runner = Agy(self.root)
        completed = subprocess.CompletedProcess(
            ["agy"], 0, json.dumps({"status": "SUCCESS", "response": "  "}), ""
        )
        with patch.object(Agy, "_invoke", return_value=completed), \
             contextlib.redirect_stdout(io.StringIO()), \
             contextlib.redirect_stderr(io.StringIO()):
            with self.assertRaisesRegex(RuntimeError, "TIMELINE_AGY_FAILED"):
                _run_agy_text(
                    self.root, runner, "some transcript",
                    {"video_id": self.video_id, "unit": "timeline_001"},
                )
        archives = list((self.root / "data" / "diagnostics" / "agy"
                         / self.video_id / "timeline").glob("*/stdout.raw.txt"))
        self.assertEqual(len(archives), 1)


if __name__ == "__main__":
    unittest.main()
